    def is_native_artifact(t):
        # a tests/**/*.tg file (canary / @test — runs natively) or a
        # tests/run_*.sh gate that executes tests.
        base = os.path.basename(t)
        return (t.startswith("tests/") and
                (t.endswith(".tg") or (base.startswith("run_") and t.endswith(".sh"))))

    def is_adversarial_artifact(t):
        # the negative/fuzz/differential/negative-ABI suites and gates.
        return (re.search(r"tests/(canary_neg|fuzz|differential|slice_safety)/", t) or
                re.search(r"(canary_neg|neg|fuzz|differential|adversarial|litmus)", t)) is not None

    def enforcing_refs_ok(text):
        # every file/dir reference in the enforcing text must exist.
        refs = re.findall(r"([A-Za-z0-9_./-]+\.(?:tg|swift|sh|py|c|h|md|json|toml))", text or "")
        refs += re.findall(r"([A-Za-z0-9_./-]+/)\b", text or "")
        for r in refs:
            if not os.path.exists(os.path.join(os.path.dirname(toml_path), r)):
                return False
        return bool(refs)

    pos = 0  # the highest ladder position whose evidence holds
    # The ladder positions above DECLARED are only reachable when the
    # DECLARED status asserts implementation (implemented/partial): an
    # unsupported/design/api-only row is DECLARED — its rejection surface
    # is implemented, but the FEATURE is not.
