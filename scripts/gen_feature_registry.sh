    else:
        derived[fid] = status

    # ── the item-36 status ladder (CALCULATED, never typed) ──────────────
    # The ladder positions and their artifact-existence derivations:
    LADDER = ["DECLARED", "IMPLEMENTED", "SEMANTICALLY_CHECKED",
              "NATIVE_TESTED", "ADVERSARIAL_TESTED", "TARGET_COMPLETE",
              "EXACT_SHA_VERIFIED", "RELEASE_GATED"]
