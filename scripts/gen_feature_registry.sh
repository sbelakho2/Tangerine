# ── TOML parsing: tomllib (3.11+) -> tomli -> the constrained fallback ────
def parse_fallback(text):
    """Parse the constrained features.toml subset:
    comments, [feature."id"] tables, key = "value", key = [...],
    key = [] (arrays may span lines; entries are quoted strings)."""
    features = {}
    current = None
    pending_key = None
    array = None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            if array is not None:
                current[pending_key] = array
                array = None
            header = line[1:-1].strip()
            m = re.match(r'feature\.\s*"([^"]+)"', header)
            if not m:
                raise ValueError("unexpected table header: " + header)
            fid = m.group(1)
            if fid not in features:
                features[fid] = {}
            current = features[fid]
            continue
        if array is not None:
            if line == "]":
                current[pending_key] = array
                array = None
                continue
            m = re.match(r'"((?:[^"\\]|\\.)*)"\s*,?$', line)
            if not m:
                raise ValueError("array entry parse failure: " + line)
            array.append(m.group(1).replace('\\"', '"').replace("\\\\", "\\"))
            continue
        m = re.match(r'([A-Za-z0-9_]+)\s*=\s*"((?:[^"\\]|\\.)*)"\s*$', line)
        if m:
            current[m.group(1)] = m.group(2).replace('\\"', '"').replace("\\\\", "\\")
            continue
        m = re.match(r'([A-Za-z0-9_]+)\s*=\s*\[\s*$', line)
        if m:
            pending_key = m.group(1)
            array = []
            continue
        m = re.match(r'([A-Za-z0-9_]+)\s*=\s*\[\]\s*$', line)
        if m:
            current[m.group(1)] = []
            continue
        raise ValueError("parse failure: " + raw)
    if array is not None:
        current[pending_key] = array
    return features

def parse_toml(text):
    try:
        import tomllib
        return tomllib.loads(text)
    except ImportError:
        pass
    try:
        import tomli
        return tomli.loads(text)
    except ImportError:
        pass
    return parse_fallback(text)

with open(toml_path, "r", encoding="utf-8") as fh:
    doc = parse_toml(fh.read())

features = doc.get("feature", {})
if not features:
    print("gen_feature_registry: no [feature.*] tables in features.toml", file=sys.stderr)
    sys.exit(1)

workflow_text = open(workflow_path, "r", encoding="utf-8").read() if os.path.exists(workflow_path) else ""

def suite_manifest(suite):
    return os.path.join(os.path.dirname(toml_path), "tests", suite, "MANIFEST")

def in_manifest(suite, relpath):
    man = suite_manifest(suite)
    if not os.path.exists(man):
        return False
    base = os.path.basename(relpath)
    with open(man, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if line.split("\t", 1)[0] == base:
                return True
    return False

def job_exists(job):
    return re.search(r"^  " + re.escape(job) + r":\s*$", workflow_text, re.M) is not None

