        sha = release_evidence.get("tested_sha") or ""
        if re.fullmatch(r"[0-9a-f]{7,40}", sha) and release_evidence.get("artifact_hashes"):
            pos = max(pos, LADDER_IDX["EXACT_SHA_VERIFIED"])
    if fid in (release_evidence.get("release_gated_features") or []):
        pos = LADDER_IDX["RELEASE_GATED"]
    ladder[fid] = LADDER[pos]

