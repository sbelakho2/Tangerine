            pos = max(pos, LADDER_IDX["SEMANTICALLY_CHECKED"])
            # NATIVE_TESTED — at least one listed artifact is a native one.
            if any(is_native_artifact(t) for t in tests):
                pos = max(pos, LADDER_IDX["NATIVE_TESTED"])
                # ADVERSARIAL_TESTED — at least one listed artifact is adversarial.
                if any(is_adversarial_artifact(t) for t in tests):
                    pos = max(pos, LADDER_IDX["ADVERSARIAL_TESTED"])
                # TARGET_COMPLETE — every declared target is SERVED (the honest
                # capability matrix; windows/wasm32 are not served) AND the
                # feature holds a native artifact.
                served = {"aarch64-apple-darwin", "x86_64-unknown-linux-gnu", "x86_64-apple-darwin"}
                if all(tgt in served for tgt in (f.get("targets") or [])) and (f.get("targets") or []):
                    pos = max(pos, LADDER_IDX["TARGET_COMPLETE"])
    # EXACT_SHA_VERIFIED / RELEASE_GATED — RUN facts: read ONLY from the
    # release-evidence file (written only by scripts/gen_status.sh
    # --release-evidence from the tested-SHA run artifacts).
