#!/usr/bin/env bash
#
# scripts/gen_feature_registry.sh — generate docs/current/feature_registry.md
# from the machine-readable features.toml.
#
# The registry is GENERATED EVIDENCE, not hand-written prose:
#   - features.toml is the single source (feature ID, summary, status,
#     supported targets, enforcing code, test references, required CI
#     jobs, suite memberships, the item-33 experimental gate).
#   - The statuses are DERIVED MECHANICALLY from the test-file existence
#     and the suite membership — the generator verifies that every listed
#     test path exists in the tree, that every named suite manifest
#     contains the listed file, and that every named CI job exists in
#     .github/workflows/ci.yml. Any drift FAILS the generation (exit
#     non-zero), so the registry can never claim an artifact that does
#     not exist.
#   - The item-36 STATUS LADDER is CALCULATED (never typed in
#     features.toml): DECLARED -> IMPLEMENTED -> SEMANTICALLY_CHECKED ->
#     NATIVE_TESTED -> ADVERSARIAL_TESTED -> TARGET_COMPLETE ->
#     EXACT_SHA_VERIFIED -> RELEASE_GATED, derived from the test
#     artifacts' existence (+ the enforcing-code references). The top two
#     positions are RUN facts: EXACT_SHA_VERIFIED and RELEASE_GATED are
#     read from build/release_evidence.json, the release-run evidence
#     file written ONLY by scripts/gen_status.sh --release-evidence —
#     never derived from source.
#   - The CI evidence-gate job regenerates the registry and runs
#     `git diff --exit-code`: a hand-edited or drifted committed registry
#     cannot merge. The generator ALSO regenerates the item-32
#     completeness model (scripts/gen_stdlib_completeness.sh) and the
#     public-API manifest (scripts/gen_api_manifest.sh), so the
#     evidence-gate run keeps every generated evidence artifact in sync
#     (the sweep job diff-gates the committed completeness artifacts).
#
# Status derivation:
#   status = "implemented"  -> "implemented + test-covered" when the
#                              tests/suites verify; "implemented +
#                              unverified" when no tests are listed.
#   status = "partial" | "api-only" | "design" | "unsupported" -> passed
#                              through verbatim.
#   experimental = true     -> the status cell carries the "experimental"
#                              marker (the item-33 stable-subset gate).
#   "implemented + run-verified at SHA" is NEVER derived here: it requires
#   the CI status-snapshot artifact (STATUS.txt generated by
#   scripts/gen_status.sh from the TESTED SHA).
#
# Usage: scripts/gen_feature_registry.sh [outfile] [ladder-json]
#   outfile defaults to docs/current/feature_registry.md.
#   ladder-json (optional) additionally writes the CALCULATED ladder
#   (feature id -> position, source-state facts only) as JSON — consumed
#   by scripts/gen_status.sh --release-evidence, which computes the
#   RELEASE_GATED list from it after the release checks pass.
# Exit status: 0 when every mechanical check holds and the registry is
# rendered; non-zero (with the file still written, so CI can diff it)
# when a test path, suite entry, CI job, or the completeness chain
# drifted.

set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOML="$ROOT/features.toml"
WORKFLOW="$ROOT/.github/workflows/ci.yml"
OUT="${1:-$ROOT/docs/current/feature_registry.md}"
LADDER_JSON="${2:-}"

if [ ! -f "$TOML" ]; then
  echo "gen_feature_registry: missing features.toml: $TOML" >&2
  exit 1
fi

# ── the item-32 completeness chain (regenerate everything the
# ── evidence-gate touches; the sweep job diff-gates the committed docs).
if ! bash "$ROOT/scripts/gen_stdlib_completeness.sh" "$ROOT/docs/current/stdlib_completeness.md"; then
  echo "gen_feature_registry: the stdlib completeness model FAILED (enumeration / contracts / experimental gating)" >&2
  exit 1
fi
if ! bash "$ROOT/scripts/gen_api_manifest.sh"; then
  echo "gen_feature_registry: the public-API manifest FAILED (extraction health)" >&2
  exit 1
fi

